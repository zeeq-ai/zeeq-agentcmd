using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;
using Zeeq.AgentCmd.Generators;

/// <summary>
/// Emits portable data from the same command models used by execution. Unknown serializer behavior
/// stays opaque: a source export cannot execute an authored context or converter to discover its wire shape.
/// </summary>
internal static class CommandManifestEmitter
{
    internal static void Emit(
        SourceProductionContext context,
        string catalog,
        IReadOnlyList<CommandModel> commands,
        IReadOnlyList<CompositeModel> composites
    )
    {
        var structural = Document(catalog, commands, composites, false);
        var disclosed = Document(catalog, commands, composites, true);
        // The export step consumes these checksum-protected markers as data, never as code.
        // The digest detects stale/corrupt extraction; registration still authenticates the publisher.
        var source = new StringBuilder("// <auto-generated/>\n#nullable enable\n")
            .Append("// agentcmd-manifest:structural:")
            .Append(Hash(structural))
            .Append(':')
            .Append(Convert.ToBase64String(Encoding.UTF8.GetBytes(structural)))
            .Append('\n')
            .Append("// agentcmd-manifest:baseline-templates:")
            .Append(Hash(disclosed))
            .Append(':')
            .Append(Convert.ToBase64String(Encoding.UTF8.GetBytes(disclosed)))
            .Append('\n')
            .Append(
                "namespace Zeeq.AgentCmd.Generated { internal static class AgentCmdManifestData {\n"
            )
            .Append("internal const string Structural = ")
            .Append(SymbolDisplay.FormatLiteral(structural, true))
            .Append(";\n")
            .Append("internal const string WithBaselineTemplates = ")
            .Append(SymbolDisplay.FormatLiteral(disclosed, true))
            .Append(";\n} }\n");
        context.AddSource(
            "AgentCmd.Manifest.g.cs",
            SourceText.From(source.ToString(), Encoding.UTF8)
        );
    }

    private static string Document(
        string catalog,
        IReadOnlyList<CommandModel> commands,
        IReadOnlyList<CompositeModel> composites,
        bool disclose
    ) =>
        Json(
            Object(
                "formatVersion",
                1,
                "catalogId",
                catalog,
                "baselineTemplatesIncluded",
                disclose,
                "commands",
                commands
                    .OrderBy(c => c.Id, StringComparer.Ordinal)
                    .Select(c =>
                        (object?)Object(
                            "id",
                            c.Id,
                            "revision",
                            c.Revision,
                            "definitionHash",
                            c.DefinitionHash,
                            "contractSignature",
                            c.ContractSignature,
                            "commandType",
                            CommandModels.RuntimeType(c.Type),
                            "input",
                            Shape(c.Parameters, c.Context, c.Contracts),
                            "output",
                            Shape(c.Result, c.Context, c.Contracts),
                            "placeholders",
                            c.ParametersShape.Where(p =>
                                    !p.Ignored && CommandModels.Scalar(p.Symbol.Type)
                                )
                                .OrderBy(p => p.Symbol.Name, StringComparer.Ordinal)
                                .Select(p => (object?)Parameter(p, c.Context)),
                            "runtimeOverrides",
                            c.ParametersShape.Where(RuntimeBindingGenerator.IsOverridable)
                                .OrderBy(p => p.Symbol.Name, StringComparer.Ordinal)
                                .Select(p => (object?)Parameter(p, c.Context)),
                            "capabilities",
                            Object(
                                "templateOverrides",
                                true,
                                "parameterOverrides",
                                c.ParametersShape.Any(RuntimeBindingGenerator.IsOverridable),
                                "inputSnapshot",
                                RuntimeBindingGenerator.IsSafeRecord(c.Parameters),
                                "requiresTypedPreflight",
                                true
                            ),
                            "validation",
                            Object(
                                "inputHook",
                                c.InputValidator is not null || c.InputValidatorInterface,
                                "resultHook",
                                c.ResultValidator is not null || c.ResultValidatorInterface
                            ),
                            "baselineTemplates",
                            disclose ? Object("system", c.System, "user", c.User) : null,
                            "defaultProfile",
                            disclose ? c.Profile : null
                        )
                    ),
                "compositions",
                composites
                    .OrderBy(c => c.Id, StringComparer.Ordinal)
                    .Select(c =>
                        (object?)Object(
                            "id",
                            c.Id,
                            "revision",
                            c.Revision,
                            "output",
                            Shape(c.Type, c.Context, c.Contracts),
                            "slots",
                            c.Parts.OrderBy(p => p.Symbol.Name, StringComparer.Ordinal)
                                .Select(p => (object?)Parameter(p, c.Context))
                        )
                    )
            )
        );

    private static object Parameter(PropertyModel property, INamedTypeSymbol? context) =>
        Object(
            "name",
            property.Symbol.Name,
            "typeId",
            CommandModels.Type(property.Symbol.Type),
            "jsonName",
            property.JsonName ?? (context is null ? property.Symbol.Name : null),
            "required",
            property.Required,
            "nullable",
            IsNullable(property.Symbol.Type)
        );

    private static object Shape(
        ITypeSymbol type,
        INamedTypeSymbol? context,
        IReadOnlyList<ContractTypeModel> contracts
    )
    {
        var reasons = new SortedSet<string>(StringComparer.Ordinal);
        object? schema = null;
        if (context is not null)
        {
            reasons.Add("authored_json_context: typed serializer verification required");
        }
        else
        {
            schema = Schema(
                type,
                contracts,
                new HashSet<ITypeSymbol>(SymbolEqualityComparer.Default),
                "$",
                reasons
            );
        }
        if (reasons.Count > 0)
        {
            schema = null;
        }
        return Object(
            "typeId",
            CommandModels.Type(type),
            "status",
            schema is null ? "opaque" : "declared",
            "reasons",
            reasons,
            "schema",
            schema,
            "signature",
            schema is null ? null : Hash("agentcmd-structural-schema-v1:" + Json(schema)),
            "verification",
            "typed-preflight-required"
        );
    }

    private static object? Schema(
        ITypeSymbol type,
        IReadOnlyList<ContractTypeModel> contracts,
        HashSet<ITypeSymbol> active,
        string path,
        SortedSet<string> reasons
    )
    {
        var nullable = IsNullable(type);
        var underlying =
            type is INamedTypeSymbol n
            && n.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T
                ? n.TypeArguments[0]
                : type.WithNullableAnnotation(NullableAnnotation.NotAnnotated);
        if (HasConverter(underlying))
        {
            reasons.Add(path + ":custom_converter");
            return null;
        }
        if (
            underlying
                .GetAttributes()
                .Any(a =>
                    a.AttributeClass?.ToDisplayString()
                        is "System.Text.Json.Serialization.JsonPolymorphicAttribute"
                            or "System.Text.Json.Serialization.JsonDerivedTypeAttribute"
                )
        )
        {
            reasons.Add(path + ":polymorphic_contract");
            return null;
        }
        if (!MetadataGenerator.IsSupported(underlying, out var unsupported))
        {
            reasons.Add(
                path + ":unsupported_contract:" + (unsupported ?? CommandModels.Type(underlying))
            );
            return null;
        }
        if (!active.Add(underlying))
        {
            reasons.Add(path + ":recursive_contract");
            return null;
        }
        var result = CoreSchema(underlying, contracts, active, path, reasons);
        active.Remove(underlying);
        return result is not null && nullable
            ? Object("anyOf", new[] { result, Object("type", "null") })
            : result;
    }

    private static object? CoreSchema(
        ITypeSymbol type,
        IReadOnlyList<ContractTypeModel> contracts,
        HashSet<ITypeSymbol> active,
        string path,
        SortedSet<string> reasons
    )
    {
        if (type.TypeKind == TypeKind.Enum)
        {
            return Integer(((INamedTypeSymbol)type).EnumUnderlyingType!.SpecialType);
        }
        switch (type.SpecialType)
        {
            case SpecialType.System_String:
                return Object("type", "string");
            case SpecialType.System_Char:
                return Object("type", "string", "minLength", 1, "maxLength", 1);
            case SpecialType.System_Boolean:
                return Object("type", "boolean");
            case SpecialType.System_Single:
            case SpecialType.System_Double:
            case SpecialType.System_Decimal:
                return Object("type", "number");
            case SpecialType.System_Byte:
            case SpecialType.System_SByte:
            case SpecialType.System_Int16:
            case SpecialType.System_UInt16:
            case SpecialType.System_Int32:
            case SpecialType.System_UInt32:
            case SpecialType.System_Int64:
            case SpecialType.System_UInt64:
                return Integer(type.SpecialType);
        }
        if (type.ToDisplayString() == "System.Guid")
        {
            return Object("type", "string", "format", "uuid");
        }
        if (type.ToDisplayString() == "System.DateOnly")
        {
            return Object("type", "string", "format", "date");
        }
        if (type is IArrayTypeSymbol array)
        {
            return array.ElementType.SpecialType == SpecialType.System_Byte
                ? Object("type", "string", "contentEncoding", "base64")
                : Object(
                    "type",
                    "array",
                    "items",
                    Schema(array.ElementType, contracts, active, path + "[]", reasons)
                );
        }
        if (type is INamedTypeSymbol named)
        {
            switch (named.OriginalDefinition.ToDisplayString())
            {
                case "System.Collections.Generic.List<T>":
                case "System.Collections.Generic.IReadOnlyList<T>":
                case "System.Collections.Immutable.ImmutableArray<T>":
                    return Object(
                        "type",
                        "array",
                        "items",
                        Schema(named.TypeArguments[0], contracts, active, path + "[]", reasons)
                    );
                case "System.Collections.Generic.Dictionary<TKey, TValue>":
                    return Object(
                        "type",
                        "object",
                        "additionalProperties",
                        Schema(named.TypeArguments[1], contracts, active, path + ".*", reasons)
                    );
            }
        }
        var contract = contracts.FirstOrDefault(c =>
            SymbolEqualityComparer.Default.Equals(c.Type, type)
        );
        if (contract is null)
        {
            reasons.Add(path + ":unknown_contract");
            return null;
        }
        var properties = new SortedDictionary<string, object?>(StringComparer.Ordinal);
        var required = new List<string>();
        foreach (
            var property in contract
                .Properties.Where(p => !p.Ignored)
                .OrderBy(p => p.Symbol.Name, StringComparer.Ordinal)
        )
        {
            var name = property.JsonName ?? property.Symbol.Name;
            if (properties.ContainsKey(name))
            {
                reasons.Add(path + ":duplicate_json_name:" + name);
                continue;
            }
            if (
                HasConverter(property.Symbol)
                || property
                    .Symbol.GetAttributes()
                    .Any(a =>
                        a.AttributeClass?.ToDisplayString()
                        == "System.Text.Json.Serialization.JsonIgnoreAttribute"
                    )
            )
            {
                reasons.Add(path + "." + name + ":custom_converter_or_conditional_ignore");
            }
            properties[name] = Schema(
                property.Symbol.Type,
                contracts,
                active,
                path + "." + name,
                reasons
            );
            if (property.Required)
            {
                required.Add(name);
            }
        }
        required.Sort(StringComparer.Ordinal);
        return Object(
            "type",
            "object",
            "properties",
            properties,
            "required",
            required,
            "additionalProperties",
            true
        );
    }

    private static object Integer(SpecialType type)
    {
        var bounds = type switch
        {
            SpecialType.System_Byte => ((object)byte.MinValue, (object)byte.MaxValue),
            SpecialType.System_SByte => ((object)sbyte.MinValue, (object)sbyte.MaxValue),
            SpecialType.System_Int16 => ((object)short.MinValue, (object)short.MaxValue),
            SpecialType.System_UInt16 => ((object)ushort.MinValue, (object)ushort.MaxValue),
            SpecialType.System_Int32 => ((object)int.MinValue, (object)int.MaxValue),
            SpecialType.System_UInt32 => ((object)uint.MinValue, (object)uint.MaxValue),
            SpecialType.System_Int64 => ((object)long.MinValue, (object)long.MaxValue),
            _ => ((object)ulong.MinValue, (object)ulong.MaxValue),
        };
        return Object("type", "integer", "minimum", bounds.Item1, "maximum", bounds.Item2);
    }

    private static bool IsNullable(ITypeSymbol type) =>
        type.NullableAnnotation == NullableAnnotation.Annotated
        || type is INamedTypeSymbol named
            && named.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T;

    private static bool HasConverter(ISymbol symbol) =>
        symbol
            .GetAttributes()
            .Any(attribute =>
            {
                for (
                    var current = attribute.AttributeClass;
                    current is not null;
                    current = current.BaseType
                )
                {
                    if (
                        current.ToDisplayString()
                        == "System.Text.Json.Serialization.JsonConverterAttribute"
                    )
                    {
                        return true;
                    }
                }
                return false;
            });

    private static SortedDictionary<string, object?> Object(params object?[] pairs)
    {
        var result = new SortedDictionary<string, object?>(StringComparer.Ordinal);
        for (var index = 0; index < pairs.Length; index += 2)
        {
            result.Add((string)pairs[index]!, pairs[index + 1]);
        }
        return result;
    }

    // A tiny data-only writer avoids loading application serializers or adding analyzer dependencies.
    private static string Json(object? value) =>
        value switch
        {
            null => "null",
            string text => Quote(text),
            bool flag => flag ? "true" : "false",
            IDictionary<string, object?> members => "{"
                + string.Join(",", members.Select(p => Quote(p.Key) + ":" + Json(p.Value)))
                + "}",
            IEnumerable<object?> items => "[" + string.Join(",", items.Select(Json)) + "]",
            IFormattable number => number.ToString(null, CultureInfo.InvariantCulture),
            _ => throw new InvalidOperationException("Unsupported manifest data."),
        };

    private static string Quote(string text)
    {
        var result = new StringBuilder("\"");
        foreach (var character in text)
        {
            if (character is '"' or '\\')
            {
                result.Append('\\').Append(character);
            }
            else if (character < 32 || character > 126)
            {
                result
                    .Append("\\u")
                    .Append(((int)character).ToString("x4", CultureInfo.InvariantCulture));
            }
            else
            {
                result.Append(character);
            }
        }
        return result.Append('"').ToString();
    }

    private static string Hash(string text)
    {
        using (var algorithm = SHA256.Create())
        {
            return string.Concat(
                algorithm
                    .ComputeHash(Encoding.UTF8.GetBytes(text))
                    .Select(b => b.ToString("x2", CultureInfo.InvariantCulture))
            );
        }
    }
}
