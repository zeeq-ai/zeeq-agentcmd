using System.Text.Json;
using System.Text.Json.Serialization;

namespace MetadataSpike.RegressionTests;

/// <summary>Compares the reported failures with STJ's independent generated contracts.</summary>
public sealed class HoldoutParityTests
{
    [Test]
    public async Task Never_preserves_the_member_in_writing_reading_and_schema()
    {
        var serializer = new MetadataSerializer();
        var value = new ConditionalIgnore { Name = "x", Note = "keep" };
        var expected = JsonSerializer.Serialize(value, RegressionOracle.Default.ConditionalIgnore);

        await Assert.That(serializer.Serialize(value)).IsEqualTo(expected);
        await Assert
            .That(serializer.Deserialize<ConditionalIgnore>(expected).Note)
            .IsEqualTo("keep");
        await Assert
            .That(
                serializer
                    .Schema<ConditionalIgnore>()
                    .GetProperty("properties")
                    .TryGetProperty("note", out _)
            )
            .IsTrue();
    }

    [Test]
    public async Task Never_overrides_the_hosts_null_ignore_default()
    {
        var serializer = new MetadataSerializer();
        serializer.Options.DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull;
        var context = new RegressionOracle(
            new JsonSerializerOptions(RegressionOracle.Default.Options)
            {
                DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull,
            }
        );
        var value = new ConditionalIgnore { Name = "x", Note = null };
        var actual = serializer.Serialize(value);

        await Assert
            .That(actual)
            .IsEqualTo(JsonSerializer.Serialize(value, context.ConditionalIgnore));
        using var json = JsonDocument.Parse(actual);
        await Assert
            .That(json.RootElement.GetProperty("note").ValueKind)
            .IsEqualTo(JsonValueKind.Null);
    }

    [Test]
    public async Task Marked_short_constructor_preserves_an_absent_init_default()
    {
        const string json = "{\"name\":\"x\"}";
        var expected = JsonSerializer.Deserialize(
            json,
            RegressionOracle.Default.ConstructorChoice
        )!;
        var serializer = new MetadataSerializer();
        var actual = serializer.Deserialize<ConstructorChoice>(json);

        await Assert.That(actual.Name).IsEqualTo(expected.Name);
        await Assert.That(actual.Count).IsEqualTo(7);
        await Assert
            .That(serializer.Serialize(actual))
            .IsEqualTo(
                JsonSerializer.Serialize(expected, RegressionOracle.Default.ConstructorChoice)
            );
    }

    [Test]
    public async Task Marked_constructor_still_accepts_an_explicit_init_value()
    {
        const string json = "{\"name\":\"x\",\"count\":45}";
        var expected = JsonSerializer.Deserialize(
            json,
            RegressionOracle.Default.ConstructorChoice
        )!;
        var actual = new MetadataSerializer().Deserialize<ConstructorChoice>(json);

        await Assert.That(actual.Name).IsEqualTo(expected.Name);
        await Assert.That(actual.Count).IsEqualTo(expected.Count);
    }

    [Test]
    public async Task Unmarked_overloads_preserve_the_public_default_constructor()
    {
        var expected = JsonSerializer.Deserialize(
            "{}",
            RegressionOracle.Default.DefaultConstructorChoice
        )!;
        var actual = new MetadataSerializer().Deserialize<DefaultConstructorChoice>("{}");

        await Assert.That(actual.Name).IsEqualTo(expected.Name);
        await Assert.That(actual.Count).IsEqualTo(expected.Count);
    }

    [Test]
    public async Task An_explicit_constructor_wins_over_a_public_default_constructor()
    {
        const string json = "{\"name\":\"explicit\"}";
        var expected = JsonSerializer.Deserialize(
            json,
            RegressionOracle.Default.MarkedConstructorWithDefault
        )!;
        var actual = new MetadataSerializer().Deserialize<MarkedConstructorWithDefault>(json);

        await Assert.That(actual.Name).IsEqualTo(expected.Name);
    }
}

// The oracle is intentionally generated by STJ. Sharing the candidate resolver
// here would let both sides repeat the same attribute or constructor mistake.
[JsonSourceGenerationOptions(
    PropertyNamingPolicy = JsonKnownNamingPolicy.CamelCase,
    RespectNullableAnnotations = true,
    RespectRequiredConstructorParameters = true
)]
[JsonSerializable(typeof(ConditionalIgnore))]
[JsonSerializable(typeof(ConstructorChoice))]
[JsonSerializable(typeof(DefaultConstructorChoice))]
[JsonSerializable(typeof(MarkedConstructorWithDefault))]
internal partial class RegressionOracle : JsonSerializerContext;
