using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace CodecSpike;

/// <summary>Discovers command roots and emits a deliberately bounded, reflection-free codec.</summary>
[Generator]
public sealed class CodecGenerator : IIncrementalGenerator
{
    private static readonly DiagnosticDescriptor Unsupported = new(
        "CODEC001",
        "Unsupported codec shape",
        "Codec cannot generate {0}: {1}",
        "Codec",
        DiagnosticSeverity.Error,
        true
    );

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var candidates = context
            .SyntaxProvider.CreateSyntaxProvider(
                static (node, _) => node is TypeDeclarationSyntax,
                static (ctx, _) =>
                    ctx.SemanticModel.GetDeclaredSymbol((TypeDeclarationSyntax)ctx.Node)
                    as INamedTypeSymbol
            )
            .Where(static symbol => symbol is not null)
            .Collect();
        context.RegisterSourceOutput(
            candidates,
            static (production, symbols) => Generate(production, symbols)
        );
    }

    private static void Generate(
        SourceProductionContext context,
        ImmutableArray<INamedTypeSymbol?> symbols
    )
    {
        var roots = new HashSet<ITypeSymbol>(SymbolEqualityComparer.IncludeNullability);
        foreach (var type in symbols.OfType<INamedTypeSymbol>())
        {
            for (var parent = type.BaseType; parent is not null; parent = parent.BaseType)
            {
                if (parent.Name == "PromptCommand" && parent.Arity == 2)
                {
                    roots.Add(parent.TypeArguments[0]);
                    roots.Add(parent.TypeArguments[1]);
                }
            }

            if (type.GetAttributes().Any(a => a.AttributeClass?.Name == "CompositeOutputAttribute"))
            {
                roots.Add(type);
            }
        }

        var models = new Dictionary<ITypeSymbol, Model>(SymbolEqualityComparer.IncludeNullability);
        var errors = new List<(ITypeSymbol Type, string Reason)>();
        foreach (var root in roots)
        {
            Discover(root, models, errors);
        }

        foreach (var error in errors)
        {
            context.ReportDiagnostic(
                Diagnostic.Create(
                    Unsupported,
                    error.Type.Locations.FirstOrDefault(),
                    error.Type.ToDisplayString(),
                    error.Reason
                )
            );
        }

        if (errors.Count != 0 || roots.Count == 0)
        {
            return;
        }

        var b = new StringBuilder();
        b.AppendLine("// <auto-generated/>");
        b.AppendLine("#nullable enable");
        b.AppendLine("namespace SerializationSpikes;");
        b.AppendLine("public sealed class CodecSerializer : ISpikeSerializer {");
        b.AppendLine("public string Name => \"generated-codec-subset\";");
        b.AppendLine(
            "private static T At<T>(global::System.Func<T> read, string segment) { try { return read(); } catch (global::System.Text.Json.JsonException ex) { var tail = ex.Path is { Length: > 1 } ? ex.Path.Substring(1) : \"\"; throw new global::System.Text.Json.JsonException(ex.Message, \"$\" + segment + tail, ex.LineNumber, ex.BytePositionInLine, ex); } catch (global::System.Exception ex) when (ex is global::System.InvalidOperationException or global::System.FormatException or global::System.OverflowException) { throw new global::System.Text.Json.JsonException(ex.Message, \"$\" + segment, null, null, ex); } }"
        );
        b.AppendLine(
            "public string Serialize<TValue>(TValue value) { using var stream = new global::System.IO.MemoryStream(); using (var w = new global::System.Text.Json.Utf8JsonWriter(stream)) {"
        );
        foreach (var root in roots)
        {
            b.Append("if (typeof(TValue) == typeof(")
                .Append(TypeName(root))
                .Append(")) { Write")
                .Append(models[root].Id)
                .Append("(w, (")
                .Append(TypeName(root))
                .AppendLine(")(object)value!); } else");
        }
        b.AppendLine(
            "throw new global::System.NotSupportedException(typeof(TValue).FullName); } return global::System.Text.Encoding.UTF8.GetString(stream.ToArray()); }"
        );
        b.AppendLine(
            "public TValue Deserialize<TValue>(string json) { try { using var doc = global::System.Text.Json.JsonDocument.Parse(json);"
        );
        foreach (var root in roots)
        {
            b.Append("if (typeof(TValue) == typeof(")
                .Append(TypeName(root))
                .Append(")) return (TValue)(object)Read")
                .Append(models[root].Id)
                .AppendLine("(doc.RootElement); ");
        }
        b.AppendLine(
            "throw new global::System.NotSupportedException(typeof(TValue).FullName); } catch (global::System.InvalidOperationException ex) { throw new global::System.Text.Json.JsonException(\"Invalid JSON value.\", ex); } catch (global::System.FormatException ex) { throw new global::System.Text.Json.JsonException(\"Invalid JSON value.\", ex); } catch (global::System.OverflowException ex) { throw new global::System.Text.Json.JsonException(\"Invalid JSON value.\", ex); } }"
        );
        b.AppendLine(
            "private static global::System.Text.Json.Nodes.JsonNode NullableObject(global::System.Text.Json.Nodes.JsonNode node) { if (node is global::System.Text.Json.Nodes.JsonObject obj && obj[\"type\"] is global::System.Text.Json.Nodes.JsonValue value && value.TryGetValue<string>(out var kind) && (kind == \"object\" || kind == \"array\")) obj[\"type\"] = new global::System.Text.Json.Nodes.JsonArray(global::System.Text.Json.Nodes.JsonValue.Create(kind), global::System.Text.Json.Nodes.JsonValue.Create(\"null\")); return node; }"
        );
        b.AppendLine("public global::System.Text.Json.JsonElement Schema<TValue>() {");
        foreach (var root in roots)
        {
            b.Append("if (typeof(TValue) == typeof(")
                .Append(TypeName(root))
                .Append(")) return global::System.Text.Json.JsonDocument.Parse(")
                .Append(root.IsReferenceType ? "NullableObject(" : "")
                .Append("Schema")
                .Append(models[root].Id)
                .Append("()")
                .Append(root.IsReferenceType ? ")" : "")
                .AppendLine(".ToJsonString()).RootElement.Clone();");
        }
        b.AppendLine("throw new global::System.NotSupportedException(typeof(TValue).FullName); }");
        foreach (var model in models.Values)
        {
            EmitModel(b, model, models);
        }
        b.AppendLine("}");
        context.AddSource("CodecSerializer.g.cs", SourceText.From(b.ToString(), Encoding.UTF8));
    }

    private static void Discover(
        ITypeSymbol type,
        Dictionary<ITypeSymbol, Model> models,
        List<(ITypeSymbol, string)> errors
    )
    {
        if (models.TryGetValue(type, out var existing))
        {
            if (!existing.Complete)
            {
                errors.Add((type, "recursive contract graphs are not supported"));
            }
            return;
        }
        if (type is INamedTypeSymbol converted)
        {
            var attribute = converted
                .GetAttributes()
                .FirstOrDefault(a =>
                    a.AttributeClass?.ToDisplayString()
                    == "System.Text.Json.Serialization.JsonConverterAttribute"
                );
            if (
                attribute?.ConstructorArguments.FirstOrDefault().Value is INamedTypeSymbol converter
            )
            {
                if (
                    converted.TypeKind == TypeKind.Enum
                    && converted.EnumUnderlyingType?.SpecialType == SpecialType.System_Int32
                    && converter.OriginalDefinition.ToDisplayString()
                        == "System.Text.Json.Serialization.JsonStringEnumConverter<TEnum>"
                )
                {
                    models.Add(
                        type,
                        new Model(type, models.Count) { Enum = true, Complete = true }
                    );
                    return;
                }
                var converterBase = converter.BaseType;
                while (
                    converterBase is not null
                    && converterBase.OriginalDefinition.ToDisplayString()
                        != "System.Text.Json.Serialization.JsonConverter<T>"
                )
                {
                    converterBase = converterBase.BaseType;
                }
                if (
                    converterBase is null
                    || !SymbolEqualityComparer.Default.Equals(converterBase.TypeArguments[0], type)
                    || converter.IsAbstract
                    || !converter.InstanceConstructors.Any(c =>
                        c.Parameters.Length == 0 && c.DeclaredAccessibility == Accessibility.Public
                    )
                )
                {
                    errors.Add((type, "converter must be a public constructible JsonConverter<T>"));
                    return;
                }
                models.Add(
                    type,
                    new Model(type, models.Count) { Converter = converter, Complete = true }
                );
                return;
            }
        }
        if (IsScalar(type))
        {
            models.Add(type, new Model(type, models.Count) { Scalar = true, Complete = true });
            return;
        }
        ITypeSymbol? element = null;
        var collection = "";
        if (type is IArrayTypeSymbol array && array.Rank == 1)
        {
            element = array.ElementType;
            collection = "array";
        }
        else if (type is INamedTypeSymbol collectionType)
        {
            var definition = collectionType.OriginalDefinition.ToDisplayString();
            if (
                definition == "System.Collections.Generic.IReadOnlyList<T>"
                || definition == "System.Collections.Immutable.ImmutableArray<T>"
            )
            {
                element = collectionType.TypeArguments[0];
                collection = definition.StartsWith(
                    "System.Collections.Immutable",
                    StringComparison.Ordinal
                )
                    ? "immutable"
                    : "list";
            }
            else if (
                definition == "System.Collections.Generic.Dictionary<TKey, TValue>"
                && collectionType.TypeArguments[0].SpecialType == SpecialType.System_String
            )
            {
                element = collectionType.TypeArguments[1];
                collection = "dictionary";
            }
        }
        if (element is not null)
        {
            var sequence = new Model(type, models.Count)
            {
                Element = element,
                Collection = collection,
            };
            models.Add(type, sequence);
            Discover(element, models, errors);
            sequence.Complete = true;
            return;
        }
        if (
            type is INamedTypeSymbol { IsAbstract: true } polyType
            && polyType
                .GetAttributes()
                .Any(a =>
                    a.AttributeClass?.ToDisplayString()
                    == "System.Text.Json.Serialization.JsonPolymorphicAttribute"
                )
        )
        {
            var poly = new Model(type, models.Count) { Polymorphic = true };
            var attribute = polyType
                .GetAttributes()
                .First(a =>
                    a.AttributeClass?.ToDisplayString()
                    == "System.Text.Json.Serialization.JsonPolymorphicAttribute"
                );
            poly.Discriminator =
                attribute
                    .NamedArguments.FirstOrDefault(p => p.Key == "TypeDiscriminatorPropertyName")
                    .Value.Value as string
                ?? "$type";
            models.Add(type, poly);
            foreach (
                var derived in polyType
                    .GetAttributes()
                    .Where(a =>
                        a.AttributeClass?.ToDisplayString()
                        == "System.Text.Json.Serialization.JsonDerivedTypeAttribute"
                    )
            )
            {
                if (
                    derived.ConstructorArguments.Length != 2
                    || derived.ConstructorArguments[0].Value is not INamedTypeSymbol child
                    || derived.ConstructorArguments[1].Value is not string tag
                )
                {
                    errors.Add((type, "polymorphism needs explicit string discriminators"));
                    continue;
                }
                poly.Derived.Add((child, tag));
                Discover(child, models, errors);
            }
            if (poly.Derived.Count == 0)
            {
                errors.Add((type, "polymorphism needs derived types"));
            }
            poly.Complete = true;
            return;
        }
        if (
            type is INamedTypeSymbol
            {
                TypeKind: TypeKind.Class,
                IsRecord: false,
                IsAbstract: false
            } initType
        )
        {
            var initModel = new Model(type, models.Count) { InitClass = true };
            models.Add(type, initModel);
            if (
                !initType.InstanceConstructors.Any(c =>
                    c.Parameters.Length == 0 && c.DeclaredAccessibility == Accessibility.Public
                )
            )
            {
                errors.Add((type, "init-only classes need a public parameterless constructor"));
            }
            foreach (
                var prop in initType
                    .GetMembers()
                    .OfType<IPropertySymbol>()
                    .Where(p => !p.IsStatic && p.DeclaredAccessibility == Accessibility.Public)
            )
            {
                if (
                    prop.GetAttributes()
                        .Any(a =>
                            a.AttributeClass?.ToDisplayString()
                            == "System.Text.Json.Serialization.JsonIgnoreAttribute"
                        )
                )
                {
                    continue;
                }
                if (
                    prop.SetMethod is null
                    || !prop.SetMethod.IsInitOnly
                    || !IsScalar(prop.Type)
                    || prop.Type.NullableAnnotation == NullableAnnotation.Annotated
                )
                {
                    errors.Add(
                        (type, "init-only class supports only non-nullable scalar init properties")
                    );
                    continue;
                }
                var declaration =
                    prop.DeclaringSyntaxReferences.FirstOrDefault()?.GetSyntax()
                    as PropertyDeclarationSyntax;
                var expression = declaration?.Initializer?.Value;
                if (expression is not null && expression is not LiteralExpressionSyntax)
                {
                    errors.Add((type, "init-only property default must be a literal"));
                    continue;
                }
                var name =
                    prop.GetAttributes()
                        .FirstOrDefault(a =>
                            a.AttributeClass?.ToDisplayString()
                            == "System.Text.Json.Serialization.JsonPropertyNameAttribute"
                        )
                        ?.ConstructorArguments.FirstOrDefault()
                        .Value as string
                    ?? char.ToLowerInvariant(prop.Name[0]) + prop.Name.Substring(1);
                initModel.InitProperties.Add(new InitProperty(prop, name, expression?.ToString()));
            }
            initModel.Complete = true;
            return;
        }
        if (
            type is not INamedTypeSymbol named
            || !named.IsRecord
            || named.IsAbstract
            || named.TypeKind != TypeKind.Class
        )
        {
            errors.Add((type, "only concrete positional record classes are supported as objects"));
            return;
        }
        if (
            named
                .GetAttributes()
                .Any(a =>
                    a.AttributeClass?.ContainingNamespace.ToDisplayString()
                    == "System.Text.Json.Serialization"
                )
        )
        {
            errors.Add((type, "JSON type attributes are not supported"));
        }
        if (
            named.BaseType is { SpecialType: not SpecialType.System_Object } parent
            && !parent
                .GetAttributes()
                .Any(a =>
                    a.AttributeClass?.ToDisplayString()
                    == "System.Text.Json.Serialization.JsonPolymorphicAttribute"
                )
        )
        {
            errors.Add((type, "record inheritance is not supported"));
        }
        var ctor = named.InstanceConstructors.FirstOrDefault(c =>
            c.Parameters.Length > 0 && c.DeclaredAccessibility == Accessibility.Public
        );
        if (ctor is null)
        {
            errors.Add((type, "a public positional constructor is required"));
            return;
        }
        var model = new Model(named, models.Count);
        models.Add(type, model);
        foreach (var parameter in ctor.Parameters)
        {
            var property = Properties(named)
                .FirstOrDefault(p =>
                    string.Equals(p.Name, parameter.Name, StringComparison.OrdinalIgnoreCase)
                );
            if (property is null || property.DeclaredAccessibility != Accessibility.Public)
            {
                errors.Add((type, "each constructor parameter must have a public property"));
                continue;
            }
            if (
                property
                    .GetAttributes()
                    .Any(a =>
                        a.AttributeClass?.ContainingNamespace.ToDisplayString()
                            == "System.Text.Json.Serialization"
                        && a.AttributeClass?.Name != "JsonPropertyNameAttribute"
                    )
            )
            {
                errors.Add(
                    (type, "JSON property attributes other than JsonPropertyName are not supported")
                );
            }
            var nameAttribute = property
                .GetAttributes()
                .FirstOrDefault(a =>
                    a.AttributeClass?.ToDisplayString()
                    == "System.Text.Json.Serialization.JsonPropertyNameAttribute"
                );
            var name =
                nameAttribute?.ConstructorArguments.FirstOrDefault().Value as string
                ?? char.ToLowerInvariant(property.Name[0]) + property.Name.Substring(1);
            model.Properties.Add(new Property(parameter, property, name));
            if (
                parameter.Type.SpecialType != SpecialType.System_String
                && parameter.Type.SpecialType != SpecialType.System_Int32
                && parameter.Type.SpecialType != SpecialType.System_Boolean
                && parameter.Type.SpecialType != SpecialType.System_Decimal
                && parameter.Type.ToDisplayString() != "System.DateOnly"
                && parameter.Type.ToDisplayString() != "System.Guid"
            )
            {
                Discover(parameter.Type, models, errors);
            }
            if (
                parameter.Type.NullableAnnotation == NullableAnnotation.Annotated
                && parameter.Type.SpecialType != SpecialType.System_String
            )
            {
                errors.Add((type, "nullable members are not supported"));
            }
            if (
                parameter.HasExplicitDefaultValue
                && parameter.ExplicitDefaultValue is not int
                && parameter.ExplicitDefaultValue is not bool
                && parameter.ExplicitDefaultValue is not string
                && parameter.ExplicitDefaultValue is not null
            )
            {
                errors.Add(
                    (
                        type,
                        "only integer, boolean, string and null constructor defaults are supported"
                    )
                );
            }
        }
        foreach (
            var property in named
                .GetMembers()
                .OfType<IPropertySymbol>()
                .Where(p => !p.IsStatic && p.DeclaredAccessibility == Accessibility.Public)
        )
        {
            if (
                !model.Properties.Any(p =>
                    SymbolEqualityComparer.Default.Equals(p.Symbol, property)
                )
            )
            {
                errors.Add((type, "additional public properties are not supported"));
            }
        }
        model.Complete = true;
    }

    private static void EmitModel(
        StringBuilder b,
        Model model,
        Dictionary<ITypeSymbol, Model> models
    )
    {
        var type = TypeName(model.Type);
        if (model.Polymorphic)
        {
            var discriminator = Lit(model.Discriminator);
            b.Append("private static void Write")
                .Append(model.Id)
                .Append("(global::System.Text.Json.Utf8JsonWriter w, ")
                .Append(type)
                .AppendLine(
                    " value) { using var stream = new global::System.IO.MemoryStream(); string tag; using (var inner = new global::System.Text.Json.Utf8JsonWriter(stream)) { switch (value) {"
                );
            foreach (var (child, tag) in model.Derived)
            {
                b.Append("case ")
                    .Append(TypeName(child))
                    .Append(" item: tag = ")
                    .Append(Lit(tag))
                    .Append("; Write")
                    .Append(models[child].Id)
                    .AppendLine("(inner, item); break;");
            }
            b.AppendLine(
                "default: throw new global::System.NotSupportedException(); } } using var doc = global::System.Text.Json.JsonDocument.Parse(stream.ToArray()); w.WriteStartObject();"
            );
            b.Append("w.WriteString(")
                .Append(discriminator)
                .AppendLine(
                    ", tag); foreach (var item in doc.RootElement.EnumerateObject()) item.WriteTo(w); w.WriteEndObject(); }"
                );
            b.Append("private static ")
                .Append(type)
                .Append(" Read")
                .Append(model.Id)
                .AppendLine(
                    "(global::System.Text.Json.JsonElement e) { using var stream = new global::System.IO.MemoryStream(); string? tag = null; var index = 0; using (var w = new global::System.Text.Json.Utf8JsonWriter(stream)) { w.WriteStartObject(); foreach (var item in e.EnumerateObject()) {"
                );
            b.Append("if (item.Name == ")
                .Append(discriminator)
                .AppendLine(
                    ") { if (tag is not null) throw new global::System.Text.Json.JsonException(); if (index != 0) throw new global::System.NotSupportedException(); tag = item.Value.GetString() ?? throw new global::System.Text.Json.JsonException(); } else item.WriteTo(w); index++; } w.WriteEndObject(); } using var doc = global::System.Text.Json.JsonDocument.Parse(stream.ToArray());"
                );
            foreach (var (child, tag) in model.Derived)
            {
                b.Append("if (tag == ")
                    .Append(Lit(tag))
                    .Append(") return Read")
                    .Append(models[child].Id)
                    .AppendLine("(doc.RootElement);");
            }
            b.AppendLine(
                "if (tag is null) throw new global::System.NotSupportedException(); throw new global::System.Text.Json.JsonException(); }"
            );
            b.Append("private static global::System.Text.Json.Nodes.JsonObject Schema")
                .Append(model.Id)
                .AppendLine("() { var variants = new global::System.Text.Json.Nodes.JsonArray();");
            foreach (var (child, tag) in model.Derived)
            {
                b.Append("{ var variant = Schema")
                    .Append(models[child].Id)
                    .Append("(); variant.Remove(\"type\"); variant[\"properties\"]!.AsObject()[")
                    .Append(discriminator)
                    .Append("] = new global::System.Text.Json.Nodes.JsonObject { [\"const\"] = ")
                    .Append(Lit(tag))
                    .AppendLine(
                        " }; variants.Add((global::System.Text.Json.Nodes.JsonNode?)variant); }"
                    );
            }
            b.Append(
                    "return new global::System.Text.Json.Nodes.JsonObject { [\"type\"] = \"object\", [\"anyOf\"] = variants, [\"required\"] = new global::System.Text.Json.Nodes.JsonArray(global::System.Text.Json.Nodes.JsonValue.Create("
                )
                .Append(discriminator)
                .AppendLine(")) }; }");
            return;
        }
        if (model.InitClass)
        {
            b.Append("private static void Write")
                .Append(model.Id)
                .Append("(global::System.Text.Json.Utf8JsonWriter w, ")
                .Append(type)
                .AppendLine(" value) { w.WriteStartObject();");
            foreach (var p in model.InitProperties)
            {
                b.Append("w.WritePropertyName(").Append(Lit(p.Name)).AppendLine(");");
                var method =
                    p.Symbol.Type.SpecialType == SpecialType.System_String ? "WriteStringValue"
                    : p.Symbol.Type.SpecialType == SpecialType.System_Boolean ? "WriteBooleanValue"
                    : "WriteNumberValue";
                b.Append("w.")
                    .Append(method)
                    .Append("(value.")
                    .Append(p.Symbol.Name)
                    .AppendLine(");");
            }
            b.AppendLine("w.WriteEndObject(); }");
            b.Append("private static ")
                .Append(type)
                .Append(" Read")
                .Append(model.Id)
                .AppendLine(
                    "(global::System.Text.Json.JsonElement e) { if (e.ValueKind != global::System.Text.Json.JsonValueKind.Object) throw new global::System.Text.Json.JsonException();"
                );
            b.Append("foreach (var item in e.EnumerateObject()) { if (")
                .Append(
                    string.Join(
                        " && ",
                        model.InitProperties.Select(p => "item.Name != " + Lit(p.Name))
                    )
                )
                .AppendLine(") throw new global::System.Text.Json.JsonException(); }");
            foreach (var p in model.InitProperties)
            {
                var name = p.Symbol.Name;
                var read = p.Symbol.Type.SpecialType switch
                {
                    SpecialType.System_String => "v"
                        + name
                        + ".GetString() ?? throw new global::System.Text.Json.JsonException()",
                    SpecialType.System_Int32 => "v" + name + ".GetInt32()",
                    SpecialType.System_Decimal => "v" + name + ".GetDecimal()",
                    _ => "v" + name + ".GetBoolean()",
                };
                read = "At(() => " + read + ", " + Lit("." + p.Name) + ")";
                var absent = p.Symbol.IsRequired
                    ? "throw new global::System.Text.Json.JsonException()"
                    : p.Default ?? "default!";
                b.Append("var p")
                    .Append(name)
                    .Append(" = e.TryGetProperty(")
                    .Append(Lit(p.Name))
                    .Append(", out var v")
                    .Append(name)
                    .Append(") ? ")
                    .Append(read)
                    .Append(" : ")
                    .Append(absent)
                    .AppendLine(";");
            }
            b.Append("return new ")
                .Append(type)
                .Append(" { ")
                .Append(
                    string.Join(
                        ", ",
                        model.InitProperties.Select(p => p.Symbol.Name + " = p" + p.Symbol.Name)
                    )
                )
                .AppendLine(" }; }");
            b.Append("private static global::System.Text.Json.Nodes.JsonObject Schema")
                .Append(model.Id)
                .AppendLine(
                    "() { var properties = new global::System.Text.Json.Nodes.JsonObject(); var required = new global::System.Text.Json.Nodes.JsonArray();"
                );
            foreach (var p in model.InitProperties)
            {
                var schemaType = p.Symbol.Type.SpecialType switch
                {
                    SpecialType.System_String => "string",
                    SpecialType.System_Int32 => "integer",
                    SpecialType.System_Decimal => "number",
                    _ => "boolean",
                };
                b.Append("properties[")
                    .Append(Lit(p.Name))
                    .Append("] = new global::System.Text.Json.Nodes.JsonObject { [\"type\"] = ")
                    .Append(Lit(schemaType))
                    .AppendLine(" };");
                if (p.Symbol.IsRequired)
                {
                    b.Append(
                            "required.Add((global::System.Text.Json.Nodes.JsonNode?)global::System.Text.Json.Nodes.JsonValue.Create("
                        )
                        .Append(Lit(p.Name))
                        .AppendLine("));");
                }
            }
            b.AppendLine(
                "return new global::System.Text.Json.Nodes.JsonObject { [\"type\"] = \"object\", [\"properties\"] = properties, [\"required\"] = required, [\"additionalProperties\"] = false }; }"
            );
            return;
        }
        if (model.Enum && model.Type is INamedTypeSymbol enumType)
        {
            var members = enumType
                .GetMembers()
                .OfType<IFieldSymbol>()
                .Where(f => f.HasConstantValue)
                .ToArray();
            b.Append("private static void Write")
                .Append(model.Id)
                .Append("(global::System.Text.Json.Utf8JsonWriter w, ")
                .Append(type)
                .AppendLine(" value) { switch (value) {");
            foreach (var member in members)
            {
                b.Append("case ")
                    .Append(type)
                    .Append('.')
                    .Append(member.Name)
                    .Append(": w.WriteStringValue(")
                    .Append(Lit(member.Name))
                    .AppendLine("); return;");
            }
            b.AppendLine("default: w.WriteNumberValue((int)value); return; } }");
            b.Append("private static ")
                .Append(type)
                .Append(" Read")
                .Append(model.Id)
                .Append(
                    "(global::System.Text.Json.JsonElement e) { if (e.ValueKind == global::System.Text.Json.JsonValueKind.Number) return ("
                )
                .Append(type)
                .AppendLine(")e.GetInt32(); var value = e.GetString();");
            foreach (var member in members)
            {
                b.Append("if (global::System.String.Equals(value, ")
                    .Append(Lit(member.Name))
                    .Append(", global::System.StringComparison.OrdinalIgnoreCase)) return ")
                    .Append(type)
                    .Append('.')
                    .Append(member.Name)
                    .AppendLine(";");
            }
            b.AppendLine("throw new global::System.Text.Json.JsonException(); }");
            b.Append("private static global::System.Text.Json.Nodes.JsonObject Schema")
                .Append(model.Id)
                .AppendLine("() { var values = new global::System.Text.Json.Nodes.JsonArray();");
            foreach (var member in members)
            {
                b.Append(
                        "values.Add((global::System.Text.Json.Nodes.JsonNode?)global::System.Text.Json.Nodes.JsonValue.Create("
                    )
                    .Append(Lit(member.Name))
                    .AppendLine("));");
            }
            b.AppendLine(
                "return new global::System.Text.Json.Nodes.JsonObject { [\"enum\"] = values }; }"
            );
            return;
        }
        if (model.Converter is not null)
        {
            var converter = TypeName(model.Converter);
            b.Append("private static void Write")
                .Append(model.Id)
                .Append("(global::System.Text.Json.Utf8JsonWriter w, ")
                .Append(type)
                .Append(" value) { new ")
                .Append(converter)
                .AppendLine(
                    "().Write(w, value, new global::System.Text.Json.JsonSerializerOptions()); }"
                );
            b.Append("private static ")
                .Append(type)
                .Append(" Read")
                .Append(model.Id)
                .Append(
                    "(global::System.Text.Json.JsonElement e) { var reader = new global::System.Text.Json.Utf8JsonReader(global::System.Text.Encoding.UTF8.GetBytes(e.GetRawText())); if (!reader.Read()) throw new global::System.Text.Json.JsonException(); return new "
                )
                .Append(converter)
                .Append("().Read(ref reader, typeof(")
                .Append(type)
                .AppendLine("), new global::System.Text.Json.JsonSerializerOptions())!; }");
            b.Append("private static global::System.Text.Json.Nodes.JsonNode Schema")
                .Append(model.Id)
                .AppendLine("() => global::System.Text.Json.Nodes.JsonValue.Create(true)!;");
            return;
        }
        if (model.Scalar)
        {
            var read = model.Type.SpecialType switch
            {
                SpecialType.System_String => "e.GetString()"
                    + (
                        model.Type.NullableAnnotation == NullableAnnotation.Annotated
                            ? ""
                            : " ?? throw new global::System.Text.Json.JsonException()"
                    ),
                SpecialType.System_Int32 => "e.GetInt32()",
                SpecialType.System_Decimal => "e.GetDecimal()",
                SpecialType.System_Boolean => "e.GetBoolean()",
                _ => throw new InvalidOperationException(),
            };
            var write = model.Type.SpecialType switch
            {
                SpecialType.System_String => "w.WriteStringValue(value);",
                SpecialType.System_Int32 or SpecialType.System_Decimal =>
                    "w.WriteNumberValue(value);",
                _ => "w.WriteBooleanValue(value);",
            };
            var schemaType = model.Type.SpecialType switch
            {
                SpecialType.System_String => "string",
                SpecialType.System_Int32 => "integer",
                SpecialType.System_Decimal => "number",
                _ => "boolean",
            };
            b.Append("private static void Write")
                .Append(model.Id)
                .Append("(global::System.Text.Json.Utf8JsonWriter w, ")
                .Append(type)
                .Append(" value) { ")
                .Append(write)
                .AppendLine(" }");
            b.Append("private static ")
                .Append(type)
                .Append(" Read")
                .Append(model.Id)
                .Append("(global::System.Text.Json.JsonElement e) => ")
                .Append(read)
                .AppendLine(";");
            b.Append("private static global::System.Text.Json.Nodes.JsonObject Schema")
                .Append(model.Id)
                .Append("() => new global::System.Text.Json.Nodes.JsonObject { [\"type\"] = ")
                .Append(Lit(schemaType))
                .AppendLine(" };");
            return;
        }
        if (model.Element is not null)
        {
            var element = TypeName(model.Element);
            var id = models[model.Element].Id;
            if (model.Collection == "dictionary")
            {
                b.Append("private static void Write")
                    .Append(model.Id)
                    .Append("(global::System.Text.Json.Utf8JsonWriter w, ")
                    .Append(type)
                    .Append(
                        " value) { w.WriteStartObject(); foreach (var item in value) { w.WritePropertyName(item.Key); Write"
                    )
                    .Append(id)
                    .AppendLine("(w, item.Value); } w.WriteEndObject(); }");
                b.Append("private static ")
                    .Append(type)
                    .Append(" Read")
                    .Append(model.Id)
                    .Append(
                        "(global::System.Text.Json.JsonElement e) { var values = new global::System.Collections.Generic.Dictionary<string, "
                    )
                    .Append(element)
                    .Append(
                        ">(); foreach (var item in e.EnumerateObject()) values[item.Name] = Read"
                    )
                    .Append(id)
                    .AppendLine("(item.Value); return values; }");
                b.Append("private static global::System.Text.Json.Nodes.JsonObject Schema")
                    .Append(model.Id)
                    .Append(
                        "() => new global::System.Text.Json.Nodes.JsonObject { [\"type\"] = \"object\", [\"additionalProperties\"] = Schema"
                    )
                    .Append(id)
                    .AppendLine("() };");
            }
            else
            {
                var result =
                    model.Collection == "array" ? "values.ToArray()"
                    : model.Collection == "immutable"
                        ? "global::System.Collections.Immutable.ImmutableArray.CreateRange(values)"
                    : "values";
                b.Append("private static void Write")
                    .Append(model.Id)
                    .Append("(global::System.Text.Json.Utf8JsonWriter w, ")
                    .Append(type)
                    .Append(" value) { w.WriteStartArray(); foreach (var item in value) ")
                    .Append(
                        model.Element.IsReferenceType
                            ? "if (item is null) w.WriteNullValue(); else "
                            : ""
                    )
                    .Append("Write")
                    .Append(id)
                    .AppendLine("(w, item); w.WriteEndArray(); }");
                b.Append("private static ")
                    .Append(type)
                    .Append(" Read")
                    .Append(model.Id)
                    .Append(
                        "(global::System.Text.Json.JsonElement e) { var values = new global::System.Collections.Generic.List<"
                    )
                    .Append(element)
                    .Append(
                        ">(); var index = 0; foreach (var item in e.EnumerateArray()) values.Add(At(() => "
                    )
                    .Append(
                        model.Element.IsReferenceType
                            ? "item.ValueKind == global::System.Text.Json.JsonValueKind.Null ? default! : "
                            : ""
                    )
                    .Append("Read")
                    .Append(id)
                    .Append("(item), \"[\" + index++ + \"]\")); return ")
                    .Append(result)
                    .AppendLine("; }");
                b.Append("private static global::System.Text.Json.Nodes.JsonObject Schema")
                    .Append(model.Id)
                    .Append(
                        "() => new global::System.Text.Json.Nodes.JsonObject { [\"type\"] = \"array\", [\"items\"] = "
                    )
                    .Append(model.Element.IsReferenceType ? "NullableObject(" : "")
                    .Append("Schema")
                    .Append(id)
                    .Append("()")
                    .Append(model.Element.IsReferenceType ? ")" : "")
                    .AppendLine(" };");
            }
            return;
        }
        b.Append("private static void Write")
            .Append(model.Id)
            .Append("(global::System.Text.Json.Utf8JsonWriter w, ")
            .Append(type)
            .AppendLine(" value) { w.WriteStartObject();");
        foreach (
            var p in model.Properties.OrderBy(p =>
                SymbolEqualityComparer.Default.Equals(p.Symbol.ContainingType, model.Type) ? 0 : 1
            )
        )
        {
            b.Append("w.WritePropertyName(").Append(Lit(p.Name)).AppendLine(");");
            var access = "value." + p.Symbol.Name;
            if (p.Parameter.Type.ToDisplayString() == "System.Guid")
            {
                b.Append("w.WriteStringValue(").Append(access).AppendLine(");");
                continue;
            }
            if (p.Parameter.Type.ToDisplayString() == "System.DateOnly")
            {
                b.Append("w.WriteStringValue(")
                    .Append(access)
                    .AppendLine(
                        ".ToString(\"O\", global::System.Globalization.CultureInfo.InvariantCulture));"
                    );
                continue;
            }
            switch (p.Parameter.Type.SpecialType)
            {
                case SpecialType.System_String:
                    b.Append("w.WriteStringValue(").Append(access).AppendLine(");");
                    break;
                case SpecialType.System_Int32:
                case SpecialType.System_Decimal:
                    b.Append("w.WriteNumberValue(").Append(access).AppendLine(");");
                    break;
                case SpecialType.System_Boolean:
                    b.Append("w.WriteBooleanValue(").Append(access).AppendLine(");");
                    break;
                default:
                    b.Append("Write")
                        .Append(models[p.Parameter.Type].Id)
                        .Append("(w, ")
                        .Append(access)
                        .AppendLine(");");
                    break;
            }
        }
        b.AppendLine("w.WriteEndObject(); }");
        b.Append("private static ")
            .Append(type)
            .Append(" Read")
            .Append(model.Id)
            .AppendLine(
                "(global::System.Text.Json.JsonElement e) { if (e.ValueKind != global::System.Text.Json.JsonValueKind.Object) throw new global::System.Text.Json.JsonException();"
            );
        b.Append("foreach (var item in e.EnumerateObject()) { if (");
        b.Append(string.Join(" && ", model.Properties.Select(p => "item.Name != " + Lit(p.Name))));
        b.AppendLine(
            ") throw new global::System.Text.Json.JsonException(\"Unknown property: \" + item.Name); }"
        );
        foreach (var p in model.Properties)
        {
            var id = p.Symbol.Name;
            var read = p.Parameter.Type.ToDisplayString() switch
            {
                "System.Guid" => "v" + id + ".GetGuid()",
                "System.DateOnly" => "global::System.DateOnly.ParseExact(v"
                    + id
                    + ".GetString()!, \"O\", global::System.Globalization.CultureInfo.InvariantCulture)",
                _ => p.Parameter.Type.SpecialType switch
                {
                    SpecialType.System_String => "v"
                        + id
                        + ".GetString()"
                        + (
                            p.Parameter.Type.NullableAnnotation == NullableAnnotation.Annotated
                                ? ""
                                : " ?? throw new global::System.Text.Json.JsonException()"
                        ),
                    SpecialType.System_Int32 => "v" + id + ".GetInt32()",
                    SpecialType.System_Decimal => "v" + id + ".GetDecimal()",
                    SpecialType.System_Boolean => "v" + id + ".GetBoolean()",
                    _ => "Read" + models[p.Parameter.Type].Id + "(v" + id + ")",
                },
            };
            read = "At(() => " + read + ", " + Lit("." + p.Name) + ")";
            var absent = p.Parameter.HasExplicitDefaultValue
                ? p.Parameter.ExplicitDefaultValue switch
                {
                    null => "null",
                    string text => Lit(text),
                    bool flag => flag ? "true" : "false",
                    _ => Convert.ToString(
                        p.Parameter.ExplicitDefaultValue,
                        System.Globalization.CultureInfo.InvariantCulture
                    )!,
                }
                : "throw new global::System.Text.Json.JsonException(\"Missing property: "
                    + p.Name
                    + "\")";
            b.Append("var p")
                .Append(id)
                .Append(" = e.TryGetProperty(")
                .Append(Lit(p.Name))
                .Append(", out var v")
                .Append(id)
                .Append(") ? ")
                .Append(read)
                .Append(" : ")
                .Append(absent)
                .AppendLine(";");
        }
        b.Append("return new ")
            .Append(type)
            .Append('(')
            .Append(string.Join(", ", model.Properties.Select(p => "p" + p.Symbol.Name)))
            .AppendLine("); }");
        b.Append("private static global::System.Text.Json.Nodes.JsonObject Schema")
            .Append(model.Id)
            .AppendLine(
                "() { var properties = new global::System.Text.Json.Nodes.JsonObject(); var required = new global::System.Text.Json.Nodes.JsonArray();"
            );
        foreach (
            var p in model.Properties.OrderBy(p =>
                SymbolEqualityComparer.Default.Equals(p.Symbol.ContainingType, model.Type) ? 0 : 1
            )
        )
        {
            var schema = p.Parameter.Type.ToDisplayString() switch
            {
                "System.Guid" =>
                    "new global::System.Text.Json.Nodes.JsonObject { [\"type\"] = \"string\", [\"format\"] = \"uuid\" }",
                "System.DateOnly" =>
                    "new global::System.Text.Json.Nodes.JsonObject { [\"type\"] = \"string\", [\"format\"] = \"date\" }",
                _ => p.Parameter.Type.SpecialType switch
                {
                    SpecialType.System_String => p.Parameter.Type.NullableAnnotation
                    == NullableAnnotation.Annotated
                        ? "new global::System.Text.Json.Nodes.JsonObject { [\"type\"] = new global::System.Text.Json.Nodes.JsonArray(global::System.Text.Json.Nodes.JsonValue.Create(\"string\"), global::System.Text.Json.Nodes.JsonValue.Create(\"null\")) }"
                        : "new global::System.Text.Json.Nodes.JsonObject { [\"type\"] = \"string\" }",
                    SpecialType.System_Int32 =>
                        "new global::System.Text.Json.Nodes.JsonObject { [\"type\"] = \"integer\" }",
                    SpecialType.System_Decimal =>
                        "new global::System.Text.Json.Nodes.JsonObject { [\"type\"] = \"number\" }",
                    SpecialType.System_Boolean =>
                        "new global::System.Text.Json.Nodes.JsonObject { [\"type\"] = \"boolean\" }",
                    _ => "Schema" + models[p.Parameter.Type].Id + "()",
                },
            };
            b.Append("properties[")
                .Append(Lit(p.Name))
                .Append("] = ")
                .Append(schema)
                .AppendLine(";");
            if (p.Parameter.HasExplicitDefaultValue)
            {
                var defaultValue = p.Parameter.ExplicitDefaultValue switch
                {
                    null => "null",
                    string text => Lit(text),
                    bool flag => flag ? "true" : "false",
                    _ => Convert.ToString(
                        p.Parameter.ExplicitDefaultValue,
                        System.Globalization.CultureInfo.InvariantCulture
                    )!,
                };
                b.Append("properties[")
                    .Append(Lit(p.Name))
                    .Append("]!.AsObject()[\"default\"] = ")
                    .Append(defaultValue)
                    .AppendLine(";");
            }
            if (!p.Parameter.HasExplicitDefaultValue)
            {
                b.Append(
                        "required.Add((global::System.Text.Json.Nodes.JsonNode?)global::System.Text.Json.Nodes.JsonValue.Create("
                    )
                    .Append(Lit(p.Name))
                    .AppendLine("));");
            }
        }
        b.AppendLine(
            "return new global::System.Text.Json.Nodes.JsonObject { [\"type\"] = \"object\", [\"properties\"] = properties, [\"required\"] = required, [\"additionalProperties\"] = false }; }"
        );
    }

    private static IEnumerable<IPropertySymbol> Properties(INamedTypeSymbol type)
    {
        for (var current = type; current is not null; current = current.BaseType)
        {
            foreach (var property in current.GetMembers().OfType<IPropertySymbol>())
            {
                yield return property;
            }
        }
    }

    private static bool IsScalar(ITypeSymbol type) =>
        type.SpecialType
            is SpecialType.System_String
                or SpecialType.System_Int32
                or SpecialType.System_Decimal
                or SpecialType.System_Boolean;

    private static string TypeName(ITypeSymbol type) =>
        type.ToDisplayString(
            SymbolDisplayFormat.FullyQualifiedFormat.WithMiscellaneousOptions(
                SymbolDisplayFormat.FullyQualifiedFormat.MiscellaneousOptions
                    | SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier
            )
        );

    private static string Lit(string value) => SymbolDisplay.FormatLiteral(value, true);

    private sealed class Model(ITypeSymbol type, int id)
    {
        public ITypeSymbol Type { get; } = type;
        public ITypeSymbol? Element { get; set; }
        public string Collection { get; set; } = "";
        public bool Scalar { get; set; }
        public bool Enum { get; set; }
        public bool InitClass { get; set; }
        public bool Polymorphic { get; set; }
        public string Discriminator { get; set; } = "$type";
        public List<(ITypeSymbol Type, string Tag)> Derived { get; } = new();
        public List<InitProperty> InitProperties { get; } = new();
        public INamedTypeSymbol? Converter { get; set; }
        public int Id { get; } = id;
        public bool Complete { get; set; }
        public List<Property> Properties { get; } = new();
    }

    private sealed class InitProperty(IPropertySymbol symbol, string name, string? value)
    {
        public IPropertySymbol Symbol { get; } = symbol;
        public string Name { get; } = name;
        public string? Default { get; } = value;
    }

    private sealed class Property(IParameterSymbol parameter, IPropertySymbol symbol, string name)
    {
        public IParameterSymbol Parameter { get; } = parameter;
        public IPropertySymbol Symbol { get; } = symbol;
        public string Name { get; } = name;
    }
