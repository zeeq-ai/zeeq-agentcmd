using System.Security.Cryptography;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

if (args.Length != 4) { Console.Error.WriteLine("LLMCMDPRE001: Expected source-list, reference-list, defines-list and output path."); return 1; }
try {
    static string[] Lines(string path) => File.ReadAllLines(path).Where(x => !string.IsNullOrWhiteSpace(x)).Distinct(StringComparer.Ordinal).ToArray();
    var sources=Lines(args[0]); var references=Lines(args[1]);
    var defines=Lines(args[2]).SelectMany(x=>x.Split(';',StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)).Distinct(StringComparer.Ordinal);
    var options=new CSharpParseOptions(LanguageVersion.Preview,preprocessorSymbols:defines);
    var trees=sources.Select(path=>CSharpSyntaxTree.ParseText(SourceText.From(File.ReadAllText(path),Encoding.UTF8),options,path)).ToArray();
    var metadata=references.Select(path=>MetadataReference.CreateFromFile(path));
    var compilation=CSharpCompilation.Create("LlmCmd.Precompile.Analysis",trees,metadata,new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary,nullableContextOptions:NullableContextOptions.Enable));
    var roots=new SortedSet<string>(StringComparer.Ordinal); var seen=new HashSet<ISymbol>(SymbolEqualityComparer.Default);
    bool failed=false;
    foreach(var tree in trees) {
        var model=compilation.GetSemanticModel(tree);
        // Aggregate roots must be visible to STJ in the same compilation as leaf roots.
        // Source generators cannot feed source to another generator in that same pass.
        foreach(var declaration in tree.GetRoot().DescendantNodes().OfType<RecordDeclarationSyntax>()) {
            if(model.GetDeclaredSymbol(declaration) is not INamedTypeSymbol record || !seen.Add(record)) continue;
            if(!record.GetAttributes().Any(a=>a.AttributeClass?.ToDisplayString()=="CommandRoot.CompositeOutputAttribute")) continue;
            if(ContainsUnresolved(record)) { Console.Error.WriteLine($"{tree.FilePath}({declaration.GetLocation().GetLineSpan().StartLinePosition.Line+1}): error LLMCMDPRE001: Composite output type is unresolved or open."); failed=true; continue; }
            roots.Add(record.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat));
        }
        foreach(var declaration in tree.GetRoot().DescendantNodes().OfType<ClassDeclarationSyntax>()) {
            if(model.GetDeclaredSymbol(declaration) is not INamedTypeSymbol cls || !seen.Add(cls) || cls.IsAbstract) continue;
            var parent=cls.BaseType;
            bool syntacticCandidate=declaration.BaseList?.Types.Any(x=>x.Type.DescendantNodesAndSelf().OfType<GenericNameSyntax>().Any(g=>g.Identifier.ValueText=="PromptCommand"))==true;
            if(parent is null || parent.TypeKind==TypeKind.Error) {
                if(syntacticCandidate) { Console.Error.WriteLine($"{tree.FilePath}({declaration.GetLocation().GetLineSpan().StartLinePosition.Line+1}): error LLMCMDPRE001: Unable to resolve PromptCommand base type."); failed=true; }
                continue;
            }
            if(parent.OriginalDefinition.MetadataName!="PromptCommand`2" || parent.OriginalDefinition.ContainingNamespace.ToDisplayString()!="CommandRoot") continue;
            foreach(var type in parent.TypeArguments) {
                if(ContainsUnresolved(type)) { Console.Error.WriteLine($"{tree.FilePath}({declaration.GetLocation().GetLineSpan().StartLinePosition.Line+1}): error LLMCMDPRE001: Command parameter/result type is unresolved or open."); failed=true; continue; }
                roots.Add(type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat));
            }
        }
    }
    if(failed) return 1;
    var text=new StringBuilder("// <auto-generated/>\n#nullable enable\n");
    if(roots.Count>0) {
        text.Append("namespace LlmCmd.Generated;\n[global::System.Text.Json.Serialization.JsonSourceGenerationOptions(RespectNullableAnnotations = true)]\n");
        foreach(var type in roots) {
            var hash=Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes(type)));
            text.Append("[global::System.Text.Json.Serialization.JsonSerializable(typeof(").Append(type).Append("), TypeInfoPropertyName = \"Type_").Append(hash).Append("\")]\n");
        }
        text.Append("internal partial class LlmCmdJsonContext : global::System.Text.Json.Serialization.JsonSerializerContext;\n");
    } else text.Append("// No direct PromptCommand subclasses in this compilation.\n");
    var target=Path.GetFullPath(args[3]); Directory.CreateDirectory(Path.GetDirectoryName(target)!);
    var contents=text.ToString(); if(!File.Exists(target) || File.ReadAllText(target)!=contents) {
        string temp=target+"."+Guid.NewGuid().ToString("N")+".tmp";
        try { File.WriteAllText(temp,contents,new UTF8Encoding(false)); File.Move(temp,target,true); } finally { if(File.Exists(temp)) File.Delete(temp); }
    }
    return 0;
} catch(Exception e) { Console.Error.WriteLine("LLMCMDPRE001: Serializer precompilation failed: " + e.Message); return 1; }
static bool ContainsUnresolved(ITypeSymbol type) => type.TypeKind is TypeKind.Error or TypeKind.TypeParameter || type is IArrayTypeSymbol a && ContainsUnresolved(a.ElementType) || type is INamedTypeSymbol n && n.TypeArguments.Any(ContainsUnresolved);
